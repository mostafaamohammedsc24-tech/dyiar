    fun localizeAmenity(code: String): String = when (code) {
        "POOL" -> if (isArabic) "مسبح خاص" else "Private Pool"
        "GARDEN" -> if (isArabic) "حديقة" else "Garden"
        "ELEVATOR" -> if (isArabic) "مصعد" else "Elevator"
        "SMART_HOME" -> if (isArabic) "منزل ذكي" else "Smart Home"
        "PARKING" -> if (isArabic) "موقف سيارات" else "Private Parking"
        "MAID_ROOM" -> if (isArabic) "غرفة خادمة" else "Maid's Room"
        "GYM" -> if (isArabic) "نادي رياضي" else "Gym & Fitness"
        else -> code
    }

    fun localizePropertyType(type: String): String = when (type) {
        "VILLA" -> villa
        "APARTMENT" -> apartment
        "PENTHOUSE" -> penthouse
        "TOWNHOUSE" -> townhouse
        "COMMERCIAL" -> commercial
        "LAND" -> land
        else -> all
    }

    fun localizeListingType(type: String): String = when (type) {
        "SALE" -> forSale
        "RENT" -> forRent
        else -> all
    }

    fun localizePropertyStatus(status: String): String = when (status) {
        "ACTIVE" -> if (isArabic) "متاح" else "Active"
        "SOLD" -> if (isArabic) "مباع" else "Sold"
        "DRAFT" -> if (isArabic) "مسودة" else "Draft"
        else -> status
    }

    fun localizeServiceStatus(status: String): String = when (status) {
        "REQUESTED" -> if (isArabic) "قيد الطلب" else "Requested"
        "CONFIRMED" -> if (isArabic) "مؤكد" else "Confirmed"
        "COMPLETED" -> if (isArabic) "مكتمل" else "Completed"
        "CANCELLED" -> if (isArabic) "ملغي" else "Cancelled"
        else -> status
    }

    fun localizeLandmarkCategory(cat: String): String = when (cat) {
        "MOSQUE" -> mosques
        "SCHOOL" -> schools
        "HOSPITAL" -> hospitals
        "RESTAURANT" -> restaurantsCat
        "STREET" -> streetsCat
        else -> servicesCat
    }
